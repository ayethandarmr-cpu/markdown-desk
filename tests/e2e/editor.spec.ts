import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
})

test('formats text with the ribbon and shows Markdown source', async ({ page }) => {
  await page.getByTestId('tab-file').click()
  await page.getByText('Blank document').click()
  const editor = page.getByTestId('editor')
  await editor.click()
  await page.keyboard.type('Hello world')
  await page.keyboard.press('Shift+Home')
  await page.getByTestId('btn-bold').click()
  await page.keyboard.press('End')
  await page.waitForTimeout(100)
  await page.keyboard.press('Enter')
  await page.getByRole('option', { name: /Heading 2/ }).click()
  await page.keyboard.type('Section')
  await page.getByRole('tab', { name: 'View', exact: true }).click()
  await page.getByTestId('view-source').click()
  await expect(page.getByTestId('source')).toHaveValue('**Hello world**\n\n## Section\n')
})

test('edits in source view flow back to the page', async ({ page }) => {
  await page.getByRole('tab', { name: 'View', exact: true }).click()
  await page.getByTestId('view-source').click()
  await page.getByTestId('source').fill('# From source\n\n- [ ] task\n')
  await page.getByTestId('view-print').click()
  await expect(page.getByTestId('editor').locator('h1')).toHaveText('From source')
  await expect(page.getByTestId('editor').locator('ul[data-type="taskList"]')).toBeVisible()
})

test('inserts a table and finds and replaces text', async ({ page }) => {
  await page.getByTestId('tab-file').click()
  await page.getByText('Blank document').click()
  await page.getByTestId('editor').click()
  await page.keyboard.type('cat cat dog')
  await page.keyboard.press('Control+h')
  await page.getByRole('textbox', { name: 'Find' }).fill('cat')
  await expect(page.getByText('1 of 2')).toBeVisible()
  await page.getByLabel('Replace with').fill('bird')
  await page.getByRole('button', { name: 'Replace all' }).click()
  await expect(page.getByTestId('editor')).toContainText('bird bird dog')
  await page.keyboard.press('Escape')
  await page.getByTestId('editor').click()
  await page.getByRole('tab', { name: 'Insert' }).click()
  await page.getByTestId('btn-table').click()
  await page.getByRole('button', { name: '3 by 2' }).click()
  await expect(page.getByTestId('editor').locator('table tr')).toHaveCount(2)
  await expect(page.getByRole('tab', { name: 'Table' })).toBeVisible()
})

test('keeps the draft after a reload', async ({ page }) => {
  await page.getByTestId('tab-file').click()
  await page.getByText('Blank document').click()
  await page.getByTestId('editor').click()
  await page.keyboard.type('Remember me')
  await page.waitForTimeout(900)
  await page.reload()
  await expect(page.getByTestId('editor')).toContainText('Remember me')
})

test('colours text and adds a toggle section that collapses', async ({ page }) => {
  await page.getByTestId('tab-file').click()
  await page.getByText('Blank document').click()
  const editor = page.getByTestId('editor')
  await editor.click()
  await page.keyboard.type('Red words')
  await page.keyboard.press('Shift+Home')
  await page.getByTestId('btn-color-menu').click()
  await page.getByRole('button', { name: 'Red', exact: true }).click()
  await expect(editor.locator('span[style*="color"]')).toHaveText('Red words')
  await page.keyboard.press('End')
  await page.waitForTimeout(100)
  await page.keyboard.press('Enter')
  await page.getByTestId('btn-toggle').click()
  await page.keyboard.type('Answer')
  await page.keyboard.press('Enter')
  await page.keyboard.type('Hidden detail')
  const toggle = editor.locator('div[data-type="details"]')
  await expect(toggle.locator('summary')).toHaveText('Answer')
  await toggle.locator('> button').click()
  await expect(toggle.getByText('Hidden detail')).toBeHidden()
  await toggle.locator('> button').click()
  await expect(toggle.getByText('Hidden detail')).toBeVisible()
  await page.screenshot({ path: 'test-results/toggle-color.png' })
  await page.getByRole('tab', { name: 'View', exact: true }).click()
  await page.getByTestId('view-source').click()
  await expect(page.getByTestId('source')).toHaveValue(
    '<span style="color: #e03131">Red words</span>\n\n<details open>\n<summary>Answer</summary>\n\nHidden detail\n\n</details>\n')
})

test('hides and shows the toolbar', async ({ page }) => {
  await expect(page.getByTestId('ribbon-body')).toBeVisible()
  await page.getByTestId('ribbon-toggle').click()
  await expect(page.getByTestId('ribbon-body')).toHaveCount(0)
  // Clicking a tab brings the toolbar back, like Word.
  await page.getByRole('tab', { name: 'Insert' }).click()
  await expect(page.getByTestId('ribbon-body')).toBeVisible()
  await page.keyboard.press('Control+F1')
  await expect(page.getByTestId('ribbon-body')).toHaveCount(0)
  await page.reload()
  await expect(page.getByTestId('ribbon-body')).toHaveCount(0)
})

test('starts with the toolbar folded on a phone', async ({ browser }) => {
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const page = await ctx.newPage()
  await page.goto('/')
  await expect(page.getByTestId('editor')).toBeVisible()
  await expect(page.getByTestId('ribbon-body')).toHaveCount(0)
  await page.getByTestId('ribbon-toggle').click()
  await expect(page.getByTestId('ribbon-body')).toBeVisible()
  await ctx.close()
})

test('suggests an edit on selected text, then accepts it', async ({ page }) => {
  await page.getByRole('tab', { name: 'View', exact: true }).click()
  await page.getByTestId('view-source').click()
  await page.getByTestId('source').fill('cat sat on the mat.\n')
  await page.getByTestId('view-print').click()
  const editor = page.getByTestId('editor')
  await editor.locator('p').first().click()
  await page.keyboard.press('Home')
  await page.waitForTimeout(100)
  for (let i = 0; i < 3; i++) await page.keyboard.press('Shift+ArrowRight')
  await page.getByTestId('btn-suggest').click()
  const box = page.getByTestId('suggest-box')
  await expect(box.locator('textarea')).toHaveValue('cat')
  await box.locator('textarea').fill('dog')
  await page.getByTestId('suggest-update').click()
  await expect(editor.locator('del.sg-del')).toHaveText('cat')
  await expect(editor.locator('ins.sg-ins')).toHaveText('dog')
  await page.getByRole('tab', { name: 'Review' }).click()
  await expect(page.getByText('Changes (1)')).toBeVisible()
  await page.getByRole('tab', { name: 'View', exact: true }).click()
  await page.getByTestId('view-source').click()
  await expect(page.getByTestId('source')).toHaveValue('<del>cat</del><ins>dog</ins> sat on the mat.\n')
  await page.getByTestId('view-print').click()
  await page.getByRole('tab', { name: 'Review' }).click()
  await page.getByTestId('accept-all').click()
  await expect(editor.locator('ins, del')).toHaveCount(0)
  await expect(editor.locator('p').first()).toHaveText('dog sat on the mat.')
})
